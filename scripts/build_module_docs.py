LINK_PATTERN = re.compile(r"\[([^\]]*)\]\(([^)]+)\)")
# モジュール文書へのリンクからファイル名だけを取り出す。`./Modules/X.md` と
# `./Documentation~/Modules/X.md` の両方に当たる。
MODULE_LINK_PATTERN = re.compile(r"\]\((?:[^)]*/)?Modules/([A-Za-z0-9_]+)\.md[^)]*\)")
CODE_SPAN_PATTERN = re.compile(r"`([^`]+)`")
BOLD_PATTERN = re.compile(r"\*\*(.+?)\*\*")
HEADING_PATTERN = re.compile(r"^(#{1,6})\s+(.+?)\s*$")
FENCE_PATTERN = re.compile(r"^\s*```\s*([^\s`]*)\s*$")
BULLET_PATTERN = re.compile(r"^(\s*)-\s+(.*)$")
ORDERED_PATTERN = re.compile(r"^(\s*)(\d+)\.\s+(.*)$")
TABLE_DIVIDER_PATTERN = re.compile(r"^\s*\|(?:\s*:?-{2,}:?\s*\|)+\s*$")
RULE_PATTERN = re.compile(r"^-{3,}\s*$")
SVG_ROOT_PATTERN = re.compile(r"<svg\b[^>]*>")
SVG_VIEWBOX_PATTERN = re.compile(r'viewBox="([\d.\s-]+)"')
PLACEHOLDER_PATTERN = re.compile("\x00(\\d+)\x00")

# 対応表に無い記法。見つけたら生成を止める。黙って素通しすると生成HTMLだけが静かに壊れる。
UNSUPPORTED_PATTERNS = (
    (re.compile(r"!\["), "画像"),
    (re.compile(r"<[a-zA-Z/!]"), "生のHTMLタグまたは自動リンク"),
    (re.compile(r"\]\["), "参照リンク"),
    (re.compile(r"~~"), "打ち消し線"),
    (re.compile(r"\[\^"), "脚注"),
    (re.compile(r"(?<!\*)\*(?!\*)"), "1つの`*`による強調"),
    (re.compile(r"(?<!\w)_[^_\s][^_]*_(?!\w)"), "`_`による強調"),
)

